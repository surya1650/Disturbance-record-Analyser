'use strict';
const assert=require('node:assert/strict');
const guide=require('../src/dranalyser/application/static/feature-guide.js');
const find=(context,id)=>guide.build(context).find(row=>row.id===id);
const empty=guide.build();
assert.equal(empty.length,6);
assert.equal(new Set(empty.map(row=>row.id)).size,6);
assert.ok(empty.every(row=>row.availability==='missing'));
assert.equal(find({hasSamples:'true'},'waveforms').availability,'missing','truthy strings cannot establish availability');
const raw={hasSamples:true};
assert.equal(find(raw,'waveforms').availability,'available');
assert.equal(find(raw,'rms-vectors').availability,'limited');
assert.match(find(raw,'rms-vectors').reason,/actual source times/);
const cursor={...raw,hasAnalogSamples:true,hasSourceTimes:true,hasNominalFrequency:true};
assert.match(find(cursor,'rms-vectors').reason,/complete trailing cycle/);
assert.ok(!find(cursor,'rms-vectors').inputs.some(text=>/four-cycle/.test(text)));
assert.ok(!find(cursor,'rms-vectors').inputs.some(text=>/source analysis/i.test(text)));
assert.match(find(cursor,'rms-vectors').what,/sample RMS.*DC.*harmonics/);
assert.match(find(cursor,'rms-vectors').what,/Fourier/);
assert.match(find({...cursor,hasNominalFrequency:'true'},'rms-vectors').reason,/valid declared nominal frequency/);
assert.match(find(raw,'conditions').reason,/Automatic timing/);
assert.ok(!find(raw,'conditions').inputs.some(text=>/Apply|A–B/.test(text)));
assert.match(find(raw,'conditions').optional.join(' '),/Manual interval adjustment is optional/);
assert.equal(find(raw,'projection').availability,'missing');
assert.ok(find(raw,'waveforms').optional.join(' ').includes('not needed'));
const noFits={...raw,analysisReady:true};
assert.equal(find(noFits,'rms-vectors').availability,'limited');
assert.equal(find(noFits,'conditions').availability,'limited');
assert.equal(find({...noFits,hasRegions:true},'conditions').availability,'limited');
assert.match(find({...noFits,hasRegions:true},'conditions').reason,/short, ongoing or incomplete/);
const ready={...noFits,hasSupportedFits:true,hasRegions:true,hasLine:true,hasLoop:true,hasWindow:true,hasSecondRecord:true};
assert.equal(find(ready,'rms-vectors').availability,'limited','technical fits alone do not establish one-cycle cursor support');
assert.match(find({...ready,...cursor},'rms-vectors').reason,/four-cycle model fits are not required/);
assert.equal(find(ready,'conditions').availability,'limited','source fit/region choices do not prove event report regions');
assert.equal(find(ready,'compare').availability,'available');
assert.equal(find(ready,'projection').availability,'limited','selected inputs must not claim eligible or verified distance');
assert.ok(find(ready,'projection').reason.includes('assumption-dependent'));
assert.equal(find({...ready,faultLoop:'AG'},'projection').availability,'limited');
assert.match(find({...ready,faultLoop:'AG'},'projection').reason,/Ground-loop.*compensation/);
assert.equal(find({...ready,hasLoop:false,faultLoop:'AB'},'projection').availability,'limited');
assert.equal(find({hasSecondRecord:true},'compare').availability,'limited');
assert.equal(find(ready,'study').availability,'missing','source choices cannot establish operational eligibility');
assert.equal(find({hasOperationalResult:true},'study').availability,'available');
assert.ok(find({},'study').optional.some(text=>/E5.*not E5 prerequisites/.test(text)));
assert.ok(!find({},'study').inputs.some(text=>/digital|settings|GPS|E3/.test(text)),'optional method or verdict facts must not block location');
assert.match(find({},'study').optional.join(' '),/E3 alone needs/);
assert.match(find({},'study').optional.join(' '),/E2 also needs usable pre-fault/);
assert.ok(find({},'study').optional.some(text=>/E4.*requires.*clock/.test(text)));
assert.ok(find({},'study').optional.some(text=>/trip indication alone/.test(text)));
const markup=guide.markup(raw);
assert.ok(markup.includes('data-guide-feature="rms-vectors"'));
assert.ok(markup.includes('data-go-feature="report"'));
assert.ok(markup.includes('Required inputs & explanation'));
assert.ok(markup.includes('Inputs needed'));
assert.ok(markup.includes('type="button"'));
const malicious=guide.markup([{id:'<img>',title:'<script>alert(1)</script>',what:'A & B',reason:'" unsafe',inputs:['<img src=x>'],optional:[],availability:'<svg>',destination:'" onclick="alert(1)',next:'Go <b>'}]);
assert.ok(!malicious.includes('<script>'));
assert.ok(!malicious.includes('<img'));
assert.ok(malicious.includes('&lt;script&gt;'));
assert.ok(malicious.includes('data-go-feature="inputs"'));
assert.ok(!malicious.includes('onclick='));
const mutated=guide.build();mutated[0].inputs.push('Untrusted change');
assert.ok(!guide.build()[0].inputs.includes('Untrusted change'));
assert.equal(guide.build(null).length,6);
console.log('Feature guidance: scoped inputs, partial readiness, unsupported ground loops, unsynchronized E5, stored study, escaping and immutable definitions passed');

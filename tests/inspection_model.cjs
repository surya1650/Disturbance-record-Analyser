const assert = require('node:assert/strict');
const m = require('../src/dranalyser/application/static/inspection-model.js');
const s=m.create({file:'first.cfg',revision:1,sample_count:100,channels:[{id:'A1'},{id:'A2'},{id:'D1'}]});
s.move('A',2); s.move('B',3);
assert.equal(m.delta([2,.0017,99],[3,.0026,0]).samples,1);
assert.ok(Math.abs(m.delta([2,.0017,99],[3,.0026,0]).seconds-.0009)<1e-15);
assert.deepEqual(m.delta([2,null,99],[3,null,0]),{samples:1,seconds:null});
assert.equal(m.value([3,.0026,null]),'Unknown');
assert.equal(m.value([3,.0026,0]),'0');
assert.deepEqual(m.nearest([[1,.001,7],[2,.003,null],[3,.004,9]],2.1),[2,.003,null]);
s.reorder('A2',-1);assert.deepEqual(s.order,['A2','A1','D1']);
s.toggle('A2');assert.equal(s.visible('A2'),false);s.toggle('A2');assert.equal(s.visible('A2'),true);
s.zoom(.5,50); assert.deepEqual(s.view,[25.25,74.75]);s.pan(1);assert.deepEqual(s.view,[49.5,99]);s.reset();assert.deepEqual(s.view,[0,99]);
s.move('A',999);assert.equal(s.pins.A,99);s.move('A',-2);assert.equal(s.pins.A,0);
s.addPin();assert.equal(s.pins.C,0);s.removePin('C');assert.equal(s.pins.C,undefined);
const first=s.request('A1');const second=s.request('A1');assert.equal(s.accept(first),false);assert.equal(s.accept(second),true);
s.invalidate();assert.equal(s.accept(second),false);
assert.equal(s.accept({...s.request('D1'),record:'other.cfg'}),false);
assert.deepEqual(m.segments([[0,0,1],[1,.001,null],[2,.05,3],[3,.051,4]],.01),[[[0,0,1]],[[2,.05,3],[3,.051,4]]]);
console.log('Inspection model: cursor/sample/time, unknowns, viewport, slots and stale-response checks passed');
